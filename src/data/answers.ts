import type { AIAnswer, Citation, Insight } from '../types'
import { CHUNKS } from './chunks'

const CHUNK_MAP = new Map(CHUNKS.map((c) => [c.id, c]))

/** 由 chunkId 构造一条 Citation（quote 取原文片段） */
export function cite(chunkId: string): Citation {
  const c = CHUNK_MAP.get(chunkId)
  if (!c) throw new Error(`Unknown chunk: ${chunkId}`)
  return {
    chunkId: c.id,
    chapterId: c.chapterId,
    chapterNumber: c.chapterNumber,
    chapterTitle: c.chapterTitle,
    page: c.page,
    quote: c.text,
  }
}

function ins(id: string, text: string): Insight {
  return { id, text }
}

